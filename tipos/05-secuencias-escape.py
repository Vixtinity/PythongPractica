#comentario
# \" -> insertar comillas dobles dentro de una cadena de texto
# \' -> insertar comillas simples dentro de una cadena de texto
# \\ -> insertar una barra invertida dentro de una cadena de texto
# \n -> salto de linea"
CURSO = "Ultimate \"Python\""
CURSO2 = 'Ultimate \'Python\''
CURSO3 = "Ultimate \\Python\\"
CURSO4 = "Ultimate \nPython"

print(CURSO)
print(CURSO2)
print(CURSO3)
print(CURSO4)
